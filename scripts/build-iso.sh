#!/usr/bin/env bash
# Build a hybrid GRUB ISO containing the AgentOS kernel and initramfs.
set -euo pipefail
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
cd "$ROOT"

need() {
    command -v "$1" >/dev/null 2>&1 || { echo "build-iso: missing '$1' (run make setup)" >&2; exit 2; }
}
need grub-mkrescue
need xorriso

COMPONENT_BIN="$ROOT/build/components/bin"
if [[ ! -x "$COMPONENT_BIN/agentos-core" ]]; then ./scripts/build-components.sh; fi
if [[ ! -f "$ROOT/build/initramfs/agentos-initramfs.cpio.gz" ]]; then ./scripts/build-initramfs.sh; fi

KERNEL="${AGENTOS_KERNEL_IMAGE:-}"
if [[ -z "$KERNEL" ]]; then
    KERNEL="$(find "$ROOT/build/kernel" -maxdepth 1 -type f -name 'bzImage-*' -print 2>/dev/null | sort -V | tail -1 || true)"
    if [[ -z "$KERNEL" ]]; then
        ./scripts/build-kernel.sh
        KERNEL="$(find "$ROOT/build/kernel" -maxdepth 1 -type f -name 'bzImage-*' -print | sort -V | tail -1)"
    fi
fi
[[ -f "$KERNEL" ]] || { echo "build-iso: kernel image not found: $KERNEL" >&2; exit 1; }

INITRAMFS="$ROOT/build/initramfs/agentos-initramfs.cpio.gz"
[[ -f "$INITRAMFS" ]] || { echo "build-iso: initramfs not found: $INITRAMFS" >&2; exit 1; }

ISO_OUT="$ROOT/build/agentos.iso"
ISO_ROOT="$ROOT/build/iso-root"
rm -rf "$ISO_ROOT"
mkdir -p "$ISO_ROOT/boot/grub"
install -Dm644 "$KERNEL" "$ISO_ROOT/boot/agentos-kernel"
install -Dm644 "$INITRAMFS" "$ISO_ROOT/boot/agentos-initramfs.img"

AUTOTEST_FLAG=""
case "${AGENTOS_AUTOTEST:-0}" in
    1|true|yes|on) AUTOTEST_FLAG="agentos.autotest=1" ;;
    0|false|no|off|'') ;;
    *) echo "build-iso: AGENTOS_AUTOTEST must be 0/1" >&2; exit 2 ;;
esac
cat > "$ISO_ROOT/boot/grub/grub.cfg" <<EOF
# Generated by scripts/build-iso.sh; keep the kernel command line explicit.
serial --unit=0 --speed=115200 --word=8 --parity=no --stop=1
terminal_input console serial
terminal_output console serial
set timeout=2
set default=0
menuentry 'AgentOS v0.1.0-dev' {
    linux /boot/agentos-kernel root=/dev/ram0 rw rdinit=/init loglevel=4 console=tty0 console=ttyS0,115200n8 $AUTOTEST_FLAG
    initrd /boot/agentos-initramfs.img
}
EOF

# grub-mkrescue supplies both i386-pc El Torito and x86_64 EFI System
# Partition images when grub-pc-bin + grub-efi-amd64-bin are installed.
export SOURCE_DATE_EPOCH="${SOURCE_DATE_EPOCH:-0}"
rm -f "$ISO_OUT"
grub-mkrescue -o "$ISO_OUT" "$ISO_ROOT" >/dev/null
sha256sum "$ISO_OUT" > "$ISO_OUT.sha256"
printf '[iso] %s\n' "$ISO_OUT"
