//! agentos-sdk CLI: scaffold new agent packages.

use agentos_sdk::AgentBuilder;

fn main() {
    let args: Vec<String> = std::env::args().collect();
    if args.len() < 3 || args[1] != "new" {
        eprintln!("AgentOS Agent SDK v{}", agentos_common::VERSION);
        eprintln!("usage: agentos-sdk new <com.vendor.name> [dir]");
        std::process::exit(2);
    }
    let id = &args[2];
    let dir = args
        .get(3)
        .cloned()
        .unwrap_or_else(|| format!("{}.agent", id.trim_start_matches("com.").replace('.', "-")));
    let name = id.rsplit('.').next().unwrap_or("Agent");
    let builder = match AgentBuilder::new(id, &capitalize(name), "0.1.0") {
        Ok(b) => b
            .description("Generated by agentos-sdk")
            .developer("You", None),
        Err(e) => {
            eprintln!("invalid agent id: {e}");
            std::process::exit(1);
        }
    };
    match builder.build_dir(std::path::Path::new(&dir)) {
        Ok(report) => {
            println!("created {dir}/ (engine: mock, no permissions requested)");
            for w in &report.warnings {
                println!("  warning: {w}");
            }
            println!(
                "next: edit {dir}/manifest.json, then install with: agentos-ctl install {dir}"
            );
        }
        Err(e) => {
            eprintln!("failed: {e}");
            std::process::exit(1);
        }
    }
}

fn capitalize(s: &str) -> String {
    let mut c = s.chars();
    match c.next() {
        Some(f) => f.to_uppercase().collect::<String>() + c.as_str(),
        None => String::new(),
    }
}
